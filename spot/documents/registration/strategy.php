<div>
    <h3>Printing Time Calculation</h3>

    <p><strong>Time per entry per system:</strong> 15 seconds</p>
    <p><strong>Total entries:</strong> 1000</p>
    <p><strong>Number of systems:</strong> 8</p>

    <hr>

    <p>
        <strong>Total printing time:</strong><br>
        (1000 × 15) ÷ 8 seconds
    </p>

    <p>
        = 1875 seconds<br>
        = 31.25 minutes
    </p>

    <p>
        <strong>Result:</strong><br>
        With 8 systems running in parallel, printing 1000 entries will take
        approximately <strong>31 minutes 15 seconds</strong>.
    </p>

    <p>
        <em>Assumption: All systems process entries continuously and have an equal workload distribution.</em>
    </p>
</div>

