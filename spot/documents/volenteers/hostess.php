<h2>Hostess / Stall Attendant</h2>

<ul>
    <li>You will be assigned a specific stall or a group of stalls.</li>
    <li>Your primary responsibility is to assist exhibitors and provide information to visitors at the stalls.</li>
    <li>Be present at the stall throughout the exhibition timings unless on a scheduled break.</li>
    <li>Ensure the stall area is clean and tidy.</li>
    <li>Assist exhibitors with simple tasks like distributing brochures, guiding visitors, or answering basic
        queries.</li>
    <li>If a visitor needs detailed information about a product or service, direct them to the exhibitor.</li>
    <li>Do not share exhibitor-specific details (like pricing, packages, or business information) unless
        explicitly permitted by the exhibitor.</li>
    <li>Coordinate with fellow volunteers to ensure continuous coverage of the stall.</li>
    <li>Report any issues or concerns to the volunteer coordinator immediately.</li>
    <li>Do not leave the stall unattended without approval from the exhibitor or coordinator.</li>
    <li>Follow the dress code and maintain a professional appearance at all times.</li>
    <li>Be approachable, friendly, and helpful to all exhibitors and visitors.</li>
</ul>