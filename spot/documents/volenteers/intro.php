<h1>Volunteer Briefing</h1>

<p>
    Welcome! As a volunteer, it is important to understand the event and the organization you are representing.
</p>

<p>
    <strong>IITM (India International Travel Mart)</strong> is one of India's leading Travel & Tourism
    Exhibition organizers.
    The event brings together businesses from the travel, tourism, hospitality and related industries to promote
    their
    services, build partnerships and generate new business opportunities.
</p>

<p>
    An <strong>Exhibition</strong> is a business event where companies showcase their products and services. It
    allows
    businesses to meet potential customers, partners and industry professionals under one roof.
</p>

<p>
    The exhibition mainly consists of two types of participants:
</p>

<ul>
    <li><strong>Seller (Exhibitor):</strong> A company that books a stall to promote its products or services
        and meet potential business partners.</li>
    <li><strong>Buyer (Trade Visitor):</strong> A visitor who attends the exhibition to explore products, meet
        exhibitors, build business relationships and discover new opportunities.</li>
</ul>

<p>
    As a volunteer, your role is to welcome visitors, guide them to the correct registration desk, provide
    accurate
    information and ensure that every delegate has a smooth and professional experience.
</p>

