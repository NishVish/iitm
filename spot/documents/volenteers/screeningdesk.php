<h2>Visitor Guidance &amp; Screening (Screening Desk)</h2>

<p>
    As the Screening Desk volunteer, you are the <strong>first point of contact</strong> for every visitor
    entering the venue.
    Your responsibility is to greet visitors, identify their purpose of visit and direct them to the correct
    registration desk.
</p>

<p>
    <strong>Active Time:</strong> <span style="color:#d9534f;">10:45 AM</span>
</p>

<h3>Your Responsibilities</h3>

<ul>
    <li>Welcome every visitor with a smile.</li>
    <li>Ask for their <strong>Business Card</strong>.</li>
    <li>Ask whether they are a <strong>Trade Visitor</strong> or an <strong>Exhibitor</strong>.</li>
    <li>Identify the industry they belong to.</li>
    <li>Guide them to the appropriate registration counter.</li>
</ul>

<h3>Questions to Ask</h3>

<ol>
    <li>May I have your business card?</li>
    <li>Are you visiting as a <strong>Trade Visitor</strong> or an <strong>Exhibitor</strong>?</li>
    <li>Which industry or company do you represent?</li>
</ol>

